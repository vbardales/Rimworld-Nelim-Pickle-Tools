// Writes ColonistRace/docs/CATALOGUE-GENES.md (eye colour genes of EyeGenes3, skin colour genes of Biotech, name + colour) and
// Tests/Pickle/Mod/Pickle/Features/pickletools-gene-gallery.feature (one photograph per gene on a bald Nelim: eyes framed close, skins on the body in underwear).
// Written 2026-10-25 at the owner's request (catalogue of eye genes and skin colour genes). Values are read from the mods on disk, not typed:
// EyeGenes3 EyeColorDefs (each FacialAnimation.EyeballColorDef names its gene and its RGB), Biotech GeneDefs_Cosmetic.xml (skinColorBase / skinColorOverride).
// A mod list that lacks a mod lacks its genes: the step "has the gene" fails and names the cause. Sheets: docs/Make-LookSheets.ps1 (prefixes eyegene, skingene).
// usage: node docs/Generate-GeneGallery.js   (from the repository root)
const fs = require('fs');
const STEAM = 'C:/Program Files (x86)/Steam/steamapps';
const eyeDir = STEAM + '/workshop/content/294100/3745223213/1.6/Defs/EyeColorDefs/';   // EyeGenes3
const skinFile = STEAM + '/common/RimWorld/Data/Biotech/Defs/GeneDefs/GeneDefs_Cosmetic.xml';
const hex = (r, g, b) => [r, g, b].map(v => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('').toUpperCase();

const eyes = [];
for (const f of fs.readdirSync(eyeDir).filter(n => n.endsWith('.xml'))) {
  const t = fs.readFileSync(eyeDir + f, 'utf8');
  for (const m of t.matchAll(/<FacialAnimation\.EyeballColorDef>([\s\S]*?)<\/FacialAnimation\.EyeballColorDef>/g)) {
    const gene = (m[1].match(/<geneDef>([^<]+)</) || [])[1];
    const rgb = (m[1].match(/<eyeballColor>RGB\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)/) || []);
    if (gene && rgb[1]) eyes.push({ name: gene, hex: hex(+rgb[1], +rgb[2], +rgb[3]) });
  }
}
eyes.sort((a, b) => a.name.localeCompare(b.name));

const skins = [];
for (const b of fs.readFileSync(skinFile, 'utf8').split(/<GeneDef[ >]/).slice(1)) {
  const name = (b.match(/<defName>([^<]+)</) || [])[1];
  const c = b.match(/<skinColor(?:Base|Override)>\(?\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/);
  if (name && c && name.startsWith('Skin_')) skins.push({ name, hex: hex(+c[1], +c[2], +c[3]) });
}

const row = (mod, list) => `| ${mod} | ${list.map(x => `${x.name}#${x.hex}`).join(', ')} |`;
fs.writeFileSync('ColonistRace/docs/CATALOGUE-GENES.md', [
  '# Genes: eye colours and skin colours',
  '',
  `Generated by \`docs/Generate-GeneGallery.js\` on 2026-10-25 from the mods on disk (EyeGenes3 EyeColorDefs, Biotech GeneDefs_Cosmetic.xml). One photograph per gene on a bald Nelim (feature \`pickletools-gene-gallery\`, map \`wsl-deps.faceparts.map\`); the sheets are cut by \`docs/Make-LookSheets.ps1\` (prefixes \`eyegene\`, \`skingene\`). Step: \`Nelim's Pickle Tools: "Nelim" has the gene "<defName>"\` (a gene of the same exclusion tag is replaced). The colour after # is the RGB of the gene.`,
  '',
  '## Eye colours',
  '',
  `${eyes.length} genes. The photograph frames the head close, lids normal, nothing else changed.`,
  '',
  '| Mod | Names |',
  '|---|---|',
  row('EyeGenes3', eyes),
  '',
  '## Skin colours',
  '',
  `${skins.length} genes. The photograph frames the whole body in underwear, hair removed.`,
  '',
  '| Mod | Names |',
  '|---|---|',
  row('Biotech', skins),
  '',
].join('\n'));

const PT = "Nelim's Pickle Tools: ";
const base = (zoomLine, lids) => [
  'Given the save "Nelims-tribe" is loaded',
  'And game speed is paused',
  `And ${PT}the item and name labels are hidden`,
  `And ${PT}the tooltips are hidden`,
  `And ${PT}the colonist bar is hidden`,
  `And ${PT}the learning helper is hidden`,
  `And ${PT}the temperature of the map is 20 degrees`,
  `And ${PT}I frame the area centred on (177, 121) at root size 6.5`,
  `And ${PT}"Nelim" stands at (176, 120) facing South`,
  `And ${PT}the other colonists are out of frame`,
  `And ${PT}"Nelim" hairstyle is "Bald"`,
  `And ${PT}"Nelim" face tattoo is "none"`,
  `And ${PT}"Nelim" mouth is "MouthNormal"`,
  `And ${PT}"Nelim" brows are "BrowNormal"`,
  `And ${PT}"Nelim" lids are "${lids}"`,
  `And ${PT}"Nelim" face skin is "SkinNormal"`,
  `And ${PT}"Nelim" eyeballs are "EyeNormal"`,
  `And ${PT}"Nelim" face head shape is "HeadNormal"`,
  `And ${PT}"Nelim" facial expression is "normal"`,
  `And ${PT}"Nelim" face is held neutral`,
  ...zoomLine,
];
const eyeBase = base([`And ${PT}the camera frames the head of "Nelim" at root size 1.6`], 'LidNormal');   // root size: smaller = closer
const skinBase = base([`And ${PT}"Nelim" wears "UnderWhere_Panties"`, `And ${PT}"Nelim" wears "UnderWhere_Bra"`, `And ${PT}I frame the cell (176, 120) at zoom 2`], 'LidNormal');
const tags = ['@requires:nelim.pickletools.screenshotstudio', '@requires:nelim.pickletools.colonistrace', '@requires:nelim.pickletools.camerazoom'];
const shot = (g, prefix) => [`When ${PT}"Nelim" has the gene "${g.name}"`, `And ${PT}I let 5 frames pass`, `And I take a screenshot "${prefix}-${g.name}"`];
const out = [...tags, 'Feature: One photograph per eye colour gene and per skin colour gene on a bald Nelim (the gene catalogue)', ''];
function scenario(title, baseLines, genes, prefix) {
  out.push(`  Scenario: ${title}`);
  baseLines.forEach(l => out.push('    ' + l));
  genes.forEach(g => shot(g, prefix).forEach(l => out.push('    ' + l)));
  out.push('');
}
const half = Math.ceil(eyes.length / 2);   // at most 25 shots per scenario (Pickle's watchdog stops a scenario at 300 s)
scenario(`gene-gallery-eyes-1: eye genes 1 to ${half} of ${eyes.length}`, eyeBase, eyes.slice(0, half), 'eyegene');
scenario(`gene-gallery-eyes-2: eye genes ${half + 1} to ${eyes.length} of ${eyes.length}`, eyeBase, eyes.slice(half), 'eyegene');
scenario(`gene-gallery-skins-1: the ${skins.length} skin colour genes`, skinBase, skins, 'skingene');
fs.writeFileSync('Tests/Pickle/Mod/Pickle/Features/pickletools-gene-gallery.feature', out.join('\n'));
console.log(`${eyes.length} eye genes, ${skins.length} skin genes`);
