// Writes the catalogue of the body parts of Erin's Rhy'aeth (Workshop 3707527452, Erin.Rhyaeth), for RWRBP (RhyaethWdiRealisticBodiesPatch):
//   ColonistRace/docs/catalogues/rhyaeth.md                                  the written table (declared in pages.json, group Mods)
//   Tests/Pickle/Mod/Pickle/Features/pickletools-rhyaeth-gallery.feature     one photograph pair (south, north) per gene that draws something
// Written 2026-11-02. Everything is read from the Defs of the mod on disk (GeneDef, HeadTypeDef, FurDef), none typed. A gene is photographed on Nelim in panties after
// `loses all genes`, so the part is the only change: south for the head, horns and face, north too for the tails and wings. Sheets: Make-LookSheets (prefix rhygene).
// usage: node Docs/Generate-RhyaethCatalogue.js   (from the repository root)
const fs = require('fs');
const MOD = 'C:/Program Files (x86)/Steam/steamapps/workshop/content/294100/3707527452/1.6/Defs/';
const files = fs.readdirSync(MOD, { recursive: true }).filter(f => f.endsWith('.xml')).map(f => f.replace(/\\/g, '/'));

const rows = [];
for (const f of files) {
  const group = f.split('/').pop().replace(/\.xml$/, '').replace(/^GeneDefs_/, '').replace(/^XenotypeDef_/, 'Xenotype ');
  for (const m of fs.readFileSync(MOD + f, 'utf8').matchAll(/<(GeneDef|HeadTypeDef|FurDef)\b([^>]*)>([\s\S]*?)<\/\1>/g)) {
    const [, kind, attrs, body] = m;
    if (/Abstract="True"/i.test(attrs)) continue;
    const name = (body.match(/<defName>([^<]+)</) || [])[1];
    if (!name) continue;
    const label = (body.match(/<label>([^<]+)</) || [])[1] || '';
    const desc = ((body.match(/<description>([\s\S]*?)<\/description>/) || [])[1] || '').replace(/\s+/g, ' ').trim();
    const tex = [...body.matchAll(/<(?:texPath|graphicPath|bodyGraphicPath)>([^<]+)</g)].map(t => t[1].trim().replace(/^Things\/Pawn\/ERN_Rhyaeth\//, ''));
    const parent = (attrs.match(/ParentName="([^"]+)"/) || [])[1] || '';
    rows.push({ file: f, group, kind, name, label, desc: desc.split(/(?<=\.) /)[0] || '', tex: [...new Set(tex)], parent });
  }
}
rows.sort((a, b) => a.group.localeCompare(b.group) || a.name.localeCompare(b.name));
const cell = s => String(s).replace(/\|/g, '/');
const md = ["# Erin's Rhy'aeth: body parts", '',
  `Generated by \`Docs/Generate-RhyaethCatalogue.js\` on 2026-11-02 from the Defs of Erin's Rhy'aeth (Workshop 3707527452, packageId Erin.Rhyaeth, needs Biotech and Vanilla Expanded Framework): ${rows.length} defs. Texture paths are under \`Things/Pawn/ERN_Rhyaeth/\`. A gene is applied with the step \`"<pawn>" has the gene "<defName>"\`; a head type is the one a head gene forces.`, ''];
md.push('## Contact sheets', '', 'One photograph per body part gene on Nelim in panties, every other gene removed first: south and north for the parts, south for the scale colours, south and east for the head type. The head is not drawn: Nelim carries the gene and the head type `ERN_RhyaethFemale` (set by name), and the silhouette stays a normal head, probably because Facial Animation draws its own head. The male head type is not photographed (it needs a male colonist).', '');
for (const g of [...new Set(rows.map(r => r.group))]) {
  const part = rows.filter(r => r.group === g);
  md.push(`## ${g}`, '', `${part.length} def${part.length > 1 ? 's' : ''}.`, '', '| defName | Label | Kind | Base | Texture | Description |', '|---|---|---|---|---|---|');
  part.forEach(r => md.push(`| \`${r.name}\` | ${cell(r.label)} | ${r.kind} | ${cell(r.parent)} | ${r.tex.map(t => '`' + t + '`').join(', ')} | ${cell(r.desc)} |`));
  md.push('');
}
fs.writeFileSync('ColonistRace/docs/catalogues/rhyaeth.md', md.join('\n'));

// Photographs: the genes that draw something (a texture of their own, or a head type they force).
const shots = rows.filter(r => r.kind === 'GeneDef' && r.tex.length > 0 || r.kind === 'GeneDef' && /Head/.test(r.group));
const PT = "Nelim's Pickle Tools: ";
const base = [
  'Given the save "Nelims-tribe" is loaded', 'And game speed is paused',
  `And ${PT}the item and name labels are hidden`, `And ${PT}the tooltips are hidden`, `And ${PT}the colonist bar is hidden`, `And ${PT}the learning helper is hidden`,
  `And ${PT}the temperature of the map is 20 degrees`, `And ${PT}I frame the area centred on (177, 121) at root size 6.5`,
  `And ${PT}"Nelim" stands at (176, 120) facing South`, `And ${PT}the other colonists are out of frame`,
  `And ${PT}"Nelim" hairstyle is "Bald"`, `And ${PT}"Nelim" face tattoo is "none"`, `And ${PT}"Nelim" mouth is "MouthNormal"`, `And ${PT}"Nelim" brows are "BrowNormal"`,
  `And ${PT}"Nelim" lids are "LidNormal"`, `And ${PT}"Nelim" face skin is "SkinNormal"`, `And ${PT}"Nelim" eyeballs are "EyeNormal"`, `And ${PT}"Nelim" face head shape is "HeadNormal"`,
  `And ${PT}"Nelim" facial expression is "normal"`, `And ${PT}"Nelim" face is held neutral`, `And ${PT}"Nelim" wears "UnderWhere_Panties"`, `And ${PT}I frame the cell (176, 120) at zoom 2`,
];
const out = ['@requires:nelim.pickletools.screenshotstudio', '@requires:nelim.pickletools.colonistrace', '@requires:nelim.pickletools.camerazoom',
  "Feature: One photograph pair per body part gene of Erin's Rhy'aeth (south and north, every other gene removed first)", ''];
const per = 10;
for (let i = 0, k = 1; i < shots.length; i += per, k++) {
  const part = shots.slice(i, i + per);
  out.push(`  Scenario: rhyaeth-gallery-${k}: body part genes ${part[0].name} to ${part[part.length - 1].name} (${part.length})`);
  base.forEach(l => out.push('    ' + l));
  for (const g of part) {
    const lines = [`When ${PT}"Nelim" loses all genes`, `And ${PT}"Nelim" has the gene "${g.name}"`, `And ${PT}"Nelim" stands at (176, 120) facing South`, `And ${PT}I let 5 frames pass`, `And I take a screenshot "rhygene-${g.name}-south"`,
      `And ${PT}"Nelim" stands at (176, 120) facing North`, `And ${PT}I let 5 frames pass`, `And I take a screenshot "rhygene-${g.name}-north"`];
    lines.forEach(l => out.push('    ' + l));
  }
  out.push('');
}
// The head: the base forces the Facial Animation head shape HeadNormal, which hides the head the gene forces (scenario 1 showed a round head); here that line is left out and the head type of the
// colonist is set by name (the def must suit the gender: Nelim is female). Photographed south and east (the snout reads in profile). The male head type needs a male colonist: not photographed.
const headGene = rows.find(r => r.kind === 'GeneDef' && /Head/.test(r.group));
const headTypes = rows.filter(r => r.kind === 'HeadTypeDef' && /Female/.test(r.name));
if (headGene && headTypes.length) {
  out.push('  Scenario: rhyaeth-gallery-head: the Rhy\'aeth head type on Nelim, south and east');
  base.filter(l => !l.includes('face head shape')).forEach(l => out.push('    ' + l));
  for (const h of headTypes) [`When ${PT}"Nelim" loses all genes`, `And ${PT}"Nelim" has the gene "${headGene.name}"`, `And ${PT}"Nelim" head type is "${h.name}"`,
    `And ${PT}"Nelim" stands at (176, 120) facing South`, `And ${PT}I let 5 frames pass`, `And I take a screenshot "rhygene-${h.name}-south"`,
    `And ${PT}"Nelim" stands at (176, 120) facing East`, `And ${PT}I let 5 frames pass`, `And I take a screenshot "rhygene-${h.name}-east"`].forEach(l => out.push('    ' + l));
  out.push('');
}
// The scale colours (skin colour genes): south only, one scenario.
const scales = rows.filter(r => r.kind === 'GeneDef' && r.parent === 'GeneSkinColorOverride');
out.push(`  Scenario: rhyaeth-gallery-scales: scale colour genes (${scales.length})`);
base.forEach(l => out.push('    ' + l));
for (const g of scales) [`When ${PT}"Nelim" loses all genes`, `And ${PT}"Nelim" has the gene "${g.name}"`, `And ${PT}I let 5 frames pass`, `And I take a screenshot "rhygene-${g.name}-south"`].forEach(l => out.push('    ' + l));
out.push('');
fs.writeFileSync('Tests/Pickle/Mod/Pickle/Features/pickletools-rhyaeth-gallery.feature', out.join('\n'));
console.log(`${rows.length} defs (${[...new Set(rows.map(r => r.group))].map(g => g + ' ' + rows.filter(r => r.group === g).length).join(', ')}); ${shots.length} genes photographed, ${Math.ceil(shots.length / per)} scenarios`);
