#!/usr/bin/env node
// Coat gallery of a Colorful Coats mod (patches and textures only, no defs): one shot per animal kind, every coat of the kind side by side
// (the original graphic plus each alternate graphic of the patch), made from the PawnKindDef blocks of the mod's Patches folder.
// Usage: node Docs/Generate-CoatGallery.js <workshopId> --pkg <packageId> [--dep <packageId>:<workshopId>]... [--skip <defName>]... [--size <kind>:<drawSize>]...
//   --skip drops a kind (a patch that lists the same animal under an old defName twice). Writes the feature, the key and the map under Tests/Pickle/.
// Written 2026-11-20 for Colorful Coats Dodos 3806766249 and Megafauna 3806766441 (Cat's catalogue request). COMPILED, NOT PLAYED.
const fs = require('fs');
const path = require('path');
const args = process.argv.slice(2);
const id = args[0];
const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
const all = (n) => args.flatMap((a, i) => (a === n ? [args[i + 1]] : []));
if (!id || !opt('--pkg')) { console.error('usage: node Docs/Generate-CoatGallery.js <workshopId> --pkg <packageId> [--dep pid:id]... [--skip defName]...'); process.exit(2); }
const pkg = opt('--pkg');
const skip = new Set(all('--skip'));
const close = false; // retired 2026-11-20: rows on a laid floor replace the close spawn   // small kinds: every animal within four cells of the map centre, one tight frame; without it spread around (150, 152) for big kinds
const root = path.join('C:/Program Files (x86)/Steam/steamapps/workshop/content/294100', id, 'Patches');
const kinds = new Map();
for (const f of fs.readdirSync(root).filter((n) => n.endsWith('.xml'))) {
  const xml = fs.readFileSync(path.join(root, f), 'utf8');
  for (const block of xml.split('<xpath>').slice(1)) {
    const m = /PawnKindDef\[defName\s*=\s*"([^"]+)"\]/.exec(block);
    if (!m || skip.has(m[1])) continue;
    const next = block.indexOf('</xpath>');
    const body = block.slice(next);
    const paths = [...body.matchAll(/<texPath>([^<]+)<\/texPath>/g)].map((x) => x[1]);
    if (paths.length && !kinds.has(m[1])) kinds.set(m[1], paths);
  }
}
if (kinds.size === 0) { console.error('no PawnKindDef patch found in ' + root); process.exit(1); }
const names = [...kinds.keys()];
let feature = `# coat gallery of workshop mod ${id} (${pkg}): ${names.length} animal kinds, one shot each, every coat side by side (original graphic first), generated by Docs/Generate-CoatGallery.js. Do not edit by hand.\n`
  + `@requires:nelim.pickletools.screenshotstudio\n@requires:nelim.pickletools.stagedecor\n@requires:nelim.pickletools.coatsteps\n@requires:nelim.pickletools.colonistrace\nFeature: coat gallery ${id}\n`;
let key = `# coat gallery key of workshop mod ${id} (${pkg}); shot per kind, left to right in spawn order coat-1... is the original graphic, then each alternate graphic (the coat index of the patch, from 0)\n`;
// Layout (Cat, 2026-11-20, dbdd rejected): a laid Concrete floor, the animals of a shot in a straight row (or two rows) in spawn order coat-1..., each at least 100 px tall in the
// 1920x1080 frame, no rock or soil in frame. The floor is 25 x 11 cells around (150, 150) (as Generate-HandSets.js), so a shot holds what fits in 16 x 9 cells (root size 5.3 at most, frame 10.6 cells tall); a kind that does not fit
// is split in parts (a, b...) of the same kind. --size <kind>:<drawSize> gives the draw size of a kind (default 2; Megafauna sizes are in its Defs), pitch = ceil(size + 0.5) cells.
const sizes = Object.fromEntries(all('--size').map((x) => { const [k, v] = x.split(':'); return [k, Number(v)]; }));
const CX = 150, CZ = 150, FW = 16, FH = 9; // frame at most 5.3 root size (10.6 cells tall) so the 11-cell-tall floor fills it
function layout(n, s) {
  const pitch = Math.ceil(s + 0.5);
  const fit = (cols, rows) => cols * pitch <= FW && rows * pitch <= FH;
  const capacity = Math.max(1, Math.floor(FW / pitch) * Math.floor(FH / pitch));
  const per = Math.min(n, capacity);
  for (const cols of [per, Math.ceil(per / 2)]) { const rows = Math.ceil(per / cols); if (fit(cols, rows) || cols === 1) return { pitch, per, cols, rows }; }
  const cols = Math.floor(FW / pitch); return { pitch, per, cols, rows: Math.ceil(per / cols) };
}
let shotsDone = 0;
for (const kind of names) {
  const coats = kinds.get(kind), n = coats.length + 1;
  const lay = layout(n, sizes[kind] || 2);
  const parts = Math.ceil(n / lay.per);
  for (let part = 0; part < parts; part++) {
    const lo = part * lay.per, hi = Math.min(n, lo + lay.per), cnt = hi - lo;
    const cols = cnt === lay.per ? lay.cols : Math.min(lay.cols, cnt), rows = Math.ceil(cnt / cols);
    const size = Math.max(rows * lay.pitch / 2, cols * lay.pitch / 3.56) + 0.8;
    const shot = `coats-${id}-${kind.replace(/[^A-Za-z0-9]+/g, '-').toLowerCase()}${parts > 1 ? '-' + 'abcdefgh'[part] : ''}`;
    feature += `
  Scenario: ${shot}: ${kind}, coats ${lo + 1} to ${hi} of ${n}
`
      + `    Given the save "test-colony" is loaded
    And game speed is paused
`
      + `    And Nelim's Pickle Tools: the eclipse of the map is ended
`
      + `    And Nelim's Pickle Tools: the area from (136, 144) to (164, 156) is cleared
`
      + `    And Nelim's Pickle Tools: I lay the floor "Concrete" from (138, 145) to (162, 155)
`;
    for (let i = lo; i < hi; i++) {
      const c = (i - lo) % cols, r = Math.floor((i - lo) / cols);
      const x = Math.round(CX - (cols - 1) * lay.pitch / 2 + c * lay.pitch), z = Math.round(CZ + (rows - 1) * lay.pitch / 2 - r * lay.pitch);
      feature += `    And Nelim's Pickle Tools: an adult animal of kind "${kind}" named "coat-${i + 1}" is spawned at (${x}, ${z})
`;
    }
    for (let i = lo; i < hi; i++) feature += `    And Nelim's Pickle Tools: the animal "coat-${i + 1}" is given coat ${i === 0 ? -1 : i - 1}
`;
    feature += `    And I set the hour to 12
    And I set the weather to "Clear"
    And I wait 60 ticks
`
      + `    And Nelim's Pickle Tools: studio presentation mode is enabled
`
      + `    And Nelim's Pickle Tools: I frame the area centred on (${CX}, ${CZ}) at root size ${size.toFixed(1)}
`
      + `    And I take a screenshot "${shot}"
    Then no errors were logged
`;
    key += `
## ${shot}: ${kind}, ${cols} per row${rows > 1 ? ', ' + rows + ' rows (row 1 = north)' : ''}, left to right in spawn order
| animal | coat index | texture |
| --- | --- | --- |
`
      + Array.from({ length: cnt }, (_, j) => { const i = lo + j; return `| coat-${i + 1} | ${i === 0 ? -1 : i - 1} | ${i === 0 ? '(original)' : coats[i - 1]} |
`; }).join('');
    shotsDone++;
  }
}
const out = path.join('Tests', 'Pickle');
fs.writeFileSync(path.join(out, 'Mod', 'Pickle', 'Features', `pickletools-coats-${id}.feature`), feature);
fs.writeFileSync(path.join(out, `coats-${id}.key.md`), key);
let map = `# Coat gallery of workshop mod ${id}, generated by Docs/Generate-CoatGallery.js.\nbrrainz.harmony 2009463077\nnelim.pickletools.screenshotstudio path:PickleTools/ScreenshotStudio/Mod\nnelim.pickletools.camerazoom path:PickleTools/CameraZoom/Mod\nnelim.pickletools.stagedecor path:PickleTools/StageDecor/Mod\nnelim.pickletools.savesteps path:PickleTools/SaveSteps/Mod\nnelim.pickletools.colonistrace path:PickleTools/ColonistRace/Mod\nnelim.pickletools.coatsteps path:PickleTools/CoatSteps/Mod\nnelim.pickletools.clearscreen path:PickleTools/ClearScreen/Mod\nnelim.pickletools path:PickleTools/Tests/Pickle/StandaloneBase/Mod\n`;
map += all('--dep').map((d) => d.replace(':', ' ') + '\n').join('') + `${pkg} ${id}\n`;
fs.writeFileSync(path.join(out, `wsl-deps.coats-${id}.map`), map);
console.log(`${id}: ${names.length} kinds, ${shotsDone} shots, ${[...kinds.values()].reduce((a, c) => a + c.length + 1, 0)} animals, wrote feature, key and map`);
console.log(names.map((k) => `${k}:${kinds.get(k).length + 1}`).join(' '));
